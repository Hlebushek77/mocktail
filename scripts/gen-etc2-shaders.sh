# scripts/gen-etc2-shaders.sh — Compiles the ETC2/EAC GPU decode and ETC2->BC
# transcode shaders.
#
#   ./scripts/gen-etc2-shaders.sh           regenerate the header (needs glslc)
#   ./scripts/gen-etc2-shaders.sh --check   exit 1 when the header is stale
#
# The SPIR-V is committed as src/graphics/generated/etc2_shaders_spv.h, so
# building Mocktail needs no shader compiler. The header carries a SHA-256 of
# the GLSL sources; --check recomputes it with sha256sum alone (no glslc), and
# the etc2_shader_header_test ctest runs it, so an edited shader without a
# regenerated header fails the tests.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SHADER_DIR="${PROJECT_ROOT}/src/graphics/shaders"
HEADER="${PROJECT_ROOT}/src/graphics/generated/etc2_shaders_spv.h"

# Shader stages that become pipelines, with the array name they get.
STAGES=(
  "etc2_decode.comp:kEtc2DecodeSpv"
  "etc2_bc.comp:kEtc2BcSpv"
)

# Every GLSL source, in byte order of the file names: the hash covers the
# names too, so renaming or adding a file also makes the header stale.
source_hash() {
  (
    cd "${SHADER_DIR}"
    LC_ALL=C find . -maxdepth 1 -type f \( -name '*.glsl' -o -name '*.comp' \) \
      -printf '%f\n' | LC_ALL=C sort | while IFS= read -r name; do
        printf '%s %s\n' "$(sha256sum < "${name}" | cut -d' ' -f1)" "${name}"
      done
  ) | sha256sum | cut -d' ' -f1
}

header_hash() {
  sed -n 's/^inline constexpr char kEtc2ShaderSourceSha256\[\] = "\([0-9a-f]*\)";$/\1/p' \
    "${HEADER}" 2>/dev/null || true
}

if [[ "${1:-}" == "--check" ]]; then
  expected="$(source_hash)"
  actual="$(header_hash)"
  if [[ "${expected}" != "${actual}" ]]; then
    echo "src/graphics/generated/etc2_shaders_spv.h is stale:" >&2
    echo "  sources ${expected}" >&2
    echo "  header  ${actual:-missing}" >&2
    echo "run scripts/gen-etc2-shaders.sh (needs glslc) and commit the header" >&2
    exit 1
  fi
  echo "etc2_shaders_spv.h matches the shader sources (${expected})"
  exit 0
fi
if [[ $# -ne 0 ]]; then
  echo "usage: $0 [--check]" >&2
  exit 2
fi

command -v glslc >/dev/null || {
  echo "glslc not found (shaderc); it is only needed to regenerate" >&2
  exit 1
}

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
hash="$(source_hash)"
{
  echo "// Generated by scripts/gen-etc2-shaders.sh from src/graphics/shaders."
  echo "// Do not edit: change the GLSL and run the script again."
  echo "// glslc ($(glslc --version | head -n1)) -mfmt=num --target-env=vulkan1.0 -O"
  echo "#ifndef MOCKTAIL_GRAPHICS_GENERATED_ETC2_SHADERS_SPV_H_"
  echo "#define MOCKTAIL_GRAPHICS_GENERATED_ETC2_SHADERS_SPV_H_"
  echo
  echo "#include <cstdint>"
  echo
  echo "namespace mocktail::graphics {"
  echo
  echo "inline constexpr char kEtc2ShaderSourceSha256[] = \"${hash}\";"
  for stage in "${STAGES[@]}"; do
    file="${stage%%:*}"
    name="${stage##*:}"
    glslc -mfmt=num --target-env=vulkan1.0 -O \
      "${SHADER_DIR}/${file}" -o "${work}/${file}.num"
    echo
    echo "// ${file}"
    echo "inline constexpr std::uint32_t ${name}[] = {"
    tr -d ' \n' < "${work}/${file}.num" | tr ',' '\n' | sed '/^$/d' |
      awk '{ printf "%s%s,", (NR % 6 == 1 ? "    " : ""), $0 }
           NR % 6 == 0 { printf "\n" } END { if (NR % 6 != 0) printf "\n" }'
    echo "};"
  done
  echo
  echo "}  // namespace mocktail::graphics"
  echo
  echo "#endif  // MOCKTAIL_GRAPHICS_GENERATED_ETC2_SHADERS_SPV_H_"
} > "${work}/header"
mkdir -p "$(dirname "${HEADER}")"
mv "${work}/header" "${HEADER}"
echo "wrote ${HEADER#"${PROJECT_ROOT}/"} (${hash})"
